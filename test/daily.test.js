'use strict';
const assert = require('node:assert');
const D = require('../www/js/daily.js');
let d = D.normalize({});
assert.strictEqual(D.status(d, '2026-10-14').day, 1);
assert.strictEqual(D.claim(d, '2026-10-14').coins, 50);
assert.strictEqual(D.claim(d, '2026-10-14').ok, false, 'no double claim same day');
for (let i = 15; i <= 20; i++) D.claim(d, '2026-10-' + i);
assert.strictEqual(d.streak, 7);
assert.strictEqual(D.REWARDS[6] > D.REWARDS[5] * 2, true, 'bigger day-7');
assert.strictEqual(D.status(d, '2026-10-21').day, 1, 'after day 7 cycle restarts');
d = D.normalize({ last: '2026-10-10', streak: 4 });
const s = D.status(d, '2026-10-14'); assert.strictEqual(s.day, 1); assert.strictEqual(s.broken, true, 'missed day resets');
d = D.normalize({ last: '2026-10-13', streak: 4 });
assert.strictEqual(D.claim(d, '2026-10-14', 2).coins, 300, "day 5 doubled");
assert.strictEqual(D.status(D.normalize({ last: '2026-10-31', streak: 2 }), '2026-11-01').day, 3, 'month boundary');
assert.strictEqual(D.normalize({ streak: 99, last: 'x', total: -1 }).streak, 0);
assert.strictEqual(D.challengeFor('2026-10-14').id, D.challengeFor('2026-10-14').id, 'deterministic');
const ids = new Set(); for (let i = 1; i <= 28; i++) ids.add(D.challengeFor('2026-02-' + String(i).padStart(2, '0')).id);
assert.ok(ids.size >= 4, 'varies by date');
d = D.normalize({});
const c = D.challengeFor('2026-10-14');
assert.strictEqual(D.claimChallenge(d, '2026-10-14').ok, false);
assert.strictEqual(D.record(d, '2026-10-14', 'nope-' + c.kind, 1), false);
let done = false; for (let i = 0; i < c.goal; i++) done = D.record(d, '2026-10-14', c.kind, 1);
assert.strictEqual(done, true);
assert.strictEqual(D.claimChallenge(d, '2026-10-14').coins, c.coins);
assert.strictEqual(D.claimChallenge(d, '2026-10-14').ok, false, 'claim once');
D.challengeStatus(d, '2026-10-15'); assert.strictEqual(d.cProg, 0, 'resets next day');
assert.strictEqual(D.CHALLENGES.every(x => x.coins > 0 && x.goal > 0), true);
const src = require('node:fs').readFileSync(__dirname + '/../www/js/daily.js', 'utf8');
assert.ok(!/Math\.random|cash|wager|bet\b/i.test(src.replace(/No cash-out, wagering/, '')), 'no randomness / cash wording');
console.log('daily tests ok');
{
  const d = D.normalize({});
  assert.strictEqual(D.double(d, '2026-10-14', 'streak'), 0, 'no 2x before claim');
  D.claim(d, '2026-10-14');
  assert.strictEqual(D.double(d, '2026-10-14', 'streak'), 50);
  assert.strictEqual(D.double(d, '2026-10-14', 'streak'), 0, '2x once');
  const ch = D.challengeFor('2026-10-14');
  for (let i = 0; i < ch.goal; i++) D.record(d, '2026-10-14', ch.kind, 1);
  D.claimChallenge(d, '2026-10-14');
  assert.strictEqual(D.double(d, '2026-10-14', 'challenge'), ch.coins);
  assert.strictEqual(D.canDouble(d, '2026-10-14', 'challenge'), false);
  console.log('daily 2x tests ok');
}
