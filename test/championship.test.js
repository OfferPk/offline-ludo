'use strict';
const assert = require('node:assert/strict');
const Championship = require('../www/js/championship.js');
let checks = 0;
const ok = (condition, message) => { assert.ok(condition, message); checks++; console.log('  ok -', message); };
console.log('championship.test.js');
const bracket = Championship.create(100, 123, 1700000000000);
ok(Championship.valid(bracket) && bracket.jackpot === 800, 'valid 8-entrant championship computes an eight-entry jackpot');
ok(bracket.opponents.length === 3 && bracket.opponents[0] === 'Ruby' && bracket.bracketWinners.length === 3, 'three playable rounds have seeded offline opponents and simulated qualifiers');
const semi = Championship.record(bracket, true, 1700000000001);
ok(semi.ok && semi.tournament.stage === 1 && semi.nextStage === 'Semi-final', 'quarter-final win advances to the semi-final');
const final = Championship.record(semi.tournament, true, 1700000000002);
ok(final.tournament.stage === 2 && final.nextStage === 'Final', 'semi-final win advances to the final');
const champ = Championship.record(final.tournament, true, 1700000000003);
ok(champ.completed && champ.tournament.status === 'champion' && champ.jackpot === 800, 'final win crowns champion and awards the jackpot');
const loss = Championship.record(bracket, false, 1700000000001);
ok(loss.eliminated && loss.tournament.stage === 0 && Championship.record(loss.tournament, true).ok === false, 'a loss eliminates the player and cannot be advanced');
ok(Championship.create(25, 1, 1) === null && !Championship.valid({}), 'unsupported buy-ins and malformed brackets are rejected');
console.log('championship checks passed (' + checks + ' checks).');
